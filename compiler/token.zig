//! Token definitions for the Kyn language.

const std = @import("std");
const source = @import("source.zig");

pub const Span = source.Span;

pub const Kind = enum {
    // literals and names
    identifier,
    int_literal,
    float_literal,
    string_literal,
    char_literal,

    // keywords
    kw_fn,
    kw_import,
    kw_private,
    kw_let,
    kw_var,
    kw_const,
    kw_struct,
    kw_union,
    kw_packed,
    kw_enum,
    kw_extern,
    kw_export,
    kw_return,
    kw_if,
    kw_else,
    kw_while,
    kw_for,
    kw_match,
    kw_break,
    kw_continue,
    kw_as,
    kw_true,
    kw_false,
    kw_null,

    // primitive types
    kw_void,
    kw_bool,
    kw_i8,
    kw_i16,
    kw_i32,
    kw_i64,
    kw_i128,
    kw_u8,
    kw_u16,
    kw_u32,
    kw_u64,
    kw_u128,
    kw_f32,
    kw_f64,
    kw_usize,
    kw_isize,
    kw_char,

    // punctuation
    l_paren,
    r_paren,
    l_brace,
    r_brace,
    l_bracket,
    r_bracket,
    comma,
    semicolon,
    colon,
    dot,
    dotdot,
    ellipsis,
    arrow,
    fat_arrow,
    at,

    // operators
    plus,
    minus,
    star,
    slash,
    percent,
    amp,
    pipe,
    caret,
    tilde,
    bang,
    equal,
    equal_equal,
    bang_equal,
    less,
    less_equal,
    greater,
    greater_equal,
    shl,
    shr,
    plus_equal,
    minus_equal,
    star_equal,
    slash_equal,
    percent_equal,
    amp_equal,
    pipe_equal,
    caret_equal,
    shl_equal,
    shr_equal,
    amp_amp,
    pipe_pipe,

    eof,

    pub fn isKeyword(self: Kind) bool {
        return @backingInt(self) >= @backingInt(Kind.kw_fn) and
            @backingInt(self) <= @backingInt(Kind.kw_null);
    }

    pub fn isPrimitiveType(self: Kind) bool {
        return @backingInt(self) >= @backingInt(Kind.kw_void) and
            @backingInt(self) <= @backingInt(Kind.kw_char);
    }
};

pub const Token = struct {
    kind: Kind,
    span: Span,
    lexeme: []const u8,

    pub fn text(self: Token) []const u8 {
        return self.lexeme;
    }
};

